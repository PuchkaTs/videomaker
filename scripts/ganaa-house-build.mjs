// Timeline and sound for the Ganaa house reel (npm run build:ganaa-house).
// Reads src/ganaa-house/plan.json and the voice clips in public/ganaa-house/vo/, lays the seven scenes
// out from the real voice lengths, and writes:
//   src/ganaa-house/cues.json      scene ranges, voice placements and word marks for the composition
//   public/ganaa-house/stems/      voice.wav, music.wav (synthesised score), sfx.wav (scene sounds)
// 48 kHz stereo float. Each voice clip is gained to about -17.5 LUFS; the score ducks under the voice.
// Synth helpers follow scripts/fitzone-h01-build.mjs; the plucked string is Karplus-Strong (a yatga-like
// tone) in D major pentatonic. Re-run after changing plan.json or a voice take.
import {execFileSync, spawnSync} from 'node:child_process';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUB = join(ROOT, 'public');
const plan = JSON.parse(readFileSync(join(ROOT, 'src/ganaa-house/plan.json'), 'utf8'));
const SR = 48000;
const TARGET = -17.5;
const MUSIC_LUFS = -27;
const SFX_PEAK_DB = -9;
const db = (v) => Math.pow(10, v / 20);

const lufs = (file) => {
  const err = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', file, '-af', 'ebur128', '-f', 'null', '-'], {encoding: 'utf8'}).stderr;
  const all = err.match(/I:\s+(-?[\d.]+) LUFS/g);
  if (!all) throw new Error(`No loudness for ${file}`);
  return Number(all.pop().match(/-?[\d.]+/)[0]);
};
const duration = (file) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], {encoding: 'utf8'}));
const decode = (file) => {
  const buf = execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-f', 'f32le', '-ac', '2', '-ar', String(SR), 'pipe:1'], {maxBuffer: 1 << 30});
  const all = new Float32Array(buf.buffer, buf.byteOffset, buf.byteLength / 4);
  const n = all.length / 2;
  const l = new Float32Array(n);
  const r = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    l[i] = all[2 * i];
    r[i] = all[2 * i + 1];
  }
  return [l, r];
};

// ---------- voice ----------
const lines = Object.fromEntries(
  plan.lines.map((line) => {
    const base = join(PUB, 'ganaa-house/vo', line.take ? `${line.id}_${line.take}` : line.id);
    const meta = JSON.parse(readFileSync(`${base}.json`, 'utf8'));
    const file = `${base}.mp3`;
    const al = meta.alignment;
    const text = al.characters.join('');
    // Start time of the first occurrence of a word (case-insensitive) in the spoken text.
    const at = (word) => {
      const i = text.toLowerCase().indexOf(word.toLowerCase());
      if (i < 0) throw new Error(`"${word}" not in ${line.id}`);
      return al.character_start_times_seconds[i];
    };
    const endOf = (word) => {
      const i = text.toLowerCase().indexOf(word.toLowerCase());
      if (i < 0) throw new Error(`"${word}" not in ${line.id}`);
      return al.character_end_times_seconds[i + word.length - 1];
    };
    const speechEnd = al.character_end_times_seconds.at(-1);
    return [line.id, {...line, file, rel: file.slice(PUB.length + 1), dur: duration(file), speechEnd, gain: TARGET - lufs(file), at, endOf}];
  }),
);

// ---------- timeline ----------
// S1 hook (V1), S2 house (V2), S3 store + workshop (V3), S4 utilities (V4), S5 location (V5),
// S6 greenhouse (V6), S7 price (V7), S8 agent (V8) plus a hold.
const r3 = (v) => +v.toFixed(3);
const cues = {_: 'Generated by scripts/ganaa-house-build.mjs from plan.json; do not edit.', duration: 0, scenes: [], voices: [], marks: {}, sfx: []};
const sfx = (type, at, extra = {}) => cues.sfx.push({type, at: r3(at), ...extra});
let t = 0;
const scene = (id, voiceId, pre, post) => {
  const v = lines[voiceId];
  const from = t;
  const at = from + pre;
  cues.voices.push({id: voiceId, file: v.rel, at: r3(at), dur: r3(v.dur), gainDb: r3(v.gain)});
  t = at + v.speechEnd + post;
  cues.scenes.push({id, from: r3(from), to: r3(t)});
  return {from, at, v};
};
const S = {};
S.S1 = scene('S1', 'V1', 0.6, 0.9);
S.S2 = scene('S2', 'V2', 0.25, 0.35);
S.S3 = scene('S3', 'V3', 0.25, 0.35);
S.S4 = scene('S4', 'V4', 0.25, 0.35);
S.S5 = scene('S5', 'V5', 0.25, 0.35);
S.S6 = scene('S6', 'V6', 0.25, 0.35);
S.S7 = scene('S7', 'V7', 0.3, 0.7);
S.S8 = scene('S8', 'V8', 0.3, 2.4);
cues.duration = r3(t);
const mk = (sc, word, d = -0.08) => r3(S[sc].at + S[sc].v.at(word) + d);
cues.marks = {
  title: r3(S.S1.at - 0.35),
  land: mk('S2', 'Долоон'),
  store: mk('S3', 'хөргүүртэй'),
  shop: mk('S3', 'тавин'),
  equip: mk('S3', 'Тоног'),
  u1: mk('S4', 'Гүний'),
  u2: mk('S4', 'цэвэр'),
  u3: mk('S4', 'Гурван'),
  u4: mk('S4', 'халаалт'),
  road: mk('S5', 'Засмал'),
  market: mk('S5', 'Хүчит'),
  school: mk('S5', 'Сургууль'),
  transit: mk('S5', 'нийтийн'),
  green: mk('S6', 'хүлэмж'),
  prod: mk('S6', 'Үйлдвэрлэл'),
  price: mk('S7', 'таван'),
  loan: mk('S7', 'Банкны'),
  name: mk('S8', 'Силвер'),
};

sfx('hit', cues.marks.title);
for (const id of ['S2', 'S3', 'S4', 'S5', 'S6', 'S7', 'S8']) sfx('whoosh', S[id].from);
['land', 'store', 'shop', 'equip', 'u1', 'u2', 'u3', 'u4', 'market', 'school', 'transit', 'green', 'prod', 'loan'].forEach((m, k) => sfx('count', cues.marks[m], {k: k % 6}));
sfx('door', cues.marks.price);
sfx('end', cues.marks.name);

// ---------- audio ----------
const N = Math.ceil(cues.duration * SR);
const stereo = () => [new Float32Array(N), new Float32Array(N)];

const voice = stereo();
const speech = [];
for (const v of cues.voices) {
  const [l, r] = decode(join(PUB, v.file));
  const g = db(v.gainDb);
  const s = Math.round(v.at * SR);
  for (let i = 0; i < l.length && s + i < N; i++) {
    voice[0][s + i] += l[i] * g;
    voice[1][s + i] += r[i] * g;
  }
  speech.push([v.at, v.at + lines[v.id].speechEnd]);
}

let seed = 20261116;
const noise = () => {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 2147483648 - 1;
};
const midi = (m) => 440 * Math.pow(2, (m - 69) / 12);
const panGains = (pan) => [Math.cos(((pan + 1) * Math.PI) / 4), Math.sin(((pan + 1) * Math.PI) / 4)];
const makeBus = () => ({dry: stereo(), wet: stereo()});
const put = (bus, at, mono, gain = 1, pan = 0, send = 0.15) => {
  const start = Math.round(at * SR);
  for (let i = 0; i < mono.length; i++) {
    const j = start + i;
    if (j < 0 || j >= N) continue;
    const p = typeof pan === 'function' ? pan(i / mono.length) : pan;
    const [gl, gr] = panGains(p);
    const v = mono[i] * gain;
    bus.dry[0][j] += v * gl;
    bus.dry[1][j] += v * gr;
    bus.wet[0][j] += v * gl * send;
    bus.wet[1][j] += v * gr * send;
  }
};
const biquad = (type, freq, q = 0.707) => {
  const w = (2 * Math.PI * Math.min(freq, SR * 0.45)) / SR;
  const cos = Math.cos(w);
  const alpha = Math.sin(w) / (2 * q);
  let b0, b1, b2;
  if (type === 'lp') [b0, b1, b2] = [(1 - cos) / 2, 1 - cos, (1 - cos) / 2];
  else if (type === 'hp') [b0, b1, b2] = [(1 + cos) / 2, -(1 + cos), (1 + cos) / 2];
  else [b0, b1, b2] = [alpha, 0, -alpha];
  const a0 = 1 + alpha;
  return {b0: b0 / a0, b1: b1 / a0, b2: b2 / a0, a1: (-2 * cos) / a0, a2: (1 - alpha) / a0};
};
const filter = (x, type, freqAt, q = 0.707) => {
  const y = new Float32Array(x.length);
  let x1 = 0, x2 = 0, y1 = 0, y2 = 0, k = null;
  for (let i = 0; i < x.length; i++) {
    if (i % 32 === 0) k = biquad(type, typeof freqAt === 'function' ? freqAt(i / x.length) : freqAt, q);
    const v = k.b0 * x[i] + k.b1 * x1 + k.b2 * x2 - k.a1 * y1 - k.a2 * y2;
    x2 = x1; x1 = x[i]; y2 = y1; y1 = v;
    y[i] = v;
  }
  return y;
};
const reverb = (x, off) => {
  const combs = [1116, 1188, 1277, 1356, 1422, 1491, 1557, 1617].map((d) => Math.round(((d + off) * SR) / 44100 * 1.25));
  const aps = [556, 441, 341, 225].map((d) => Math.round(((d + off) * SR) / 44100));
  const out = new Float32Array(x.length);
  for (const d of combs) {
    const buf = new Float32Array(d);
    let idx = 0, lp = 0;
    for (let i = 0; i < x.length; i++) {
      const y = buf[idx];
      lp = y * 0.55 + lp * 0.45;
      buf[idx] = x[i] + lp * 0.86;
      idx = (idx + 1) % d;
      out[i] += y / combs.length;
    }
  }
  for (const d of aps) {
    const buf = new Float32Array(d);
    let idx = 0;
    for (let i = 0; i < x.length; i++) {
      const b = buf[idx];
      buf[idx] = out[i] + b * 0.5;
      out[i] = b - out[i];
      idx = (idx + 1) % d;
    }
  }
  return out;
};
const flatten = (bus, send = 0.9) => {
  const verb = [reverb(bus.wet[0], 0), reverb(bus.wet[1], 23)];
  return [0, 1].map((ch) => {
    const out = new Float32Array(N);
    for (let i = 0; i < N; i++) out[i] = bus.dry[ch][i] + verb[ch][i] * send;
    return out;
  });
};

// Plucked string (Karplus-Strong) with a soft body resonance: a yatga-like tone.
const yatga = (note, dur = 2.4, bright = 0.5) => {
  const n = Math.round(dur * SR);
  const out = new Float32Array(n);
  const p = Math.round(SR / midi(note));
  const buf = new Float32Array(p);
  let last = 0;
  for (let i = 0; i < p; i++) {
    last = last * (1 - bright) + noise() * bright;
    buf[i] = last;
  }
  let idx = 0;
  const decay = 0.4985 + Math.min(0.0012, 0.0006 * (60 / note));
  for (let i = 0; i < n; i++) {
    const nxt = (idx + 1) % p;
    const v = (buf[idx] + buf[nxt]) * decay;
    out[i] = buf[idx];
    buf[idx] = v;
    idx = nxt;
  }
  for (let i = 0; i < n; i++) out[i] *= Math.min(1, (n - i) / (0.2 * SR));
  return filter(out, 'lp', 3800);
};
const pad = (notes, dur, detune = 0, cutoff = 1100) => {
  const rel = 1.6;
  const n = Math.round((dur + rel) * SR);
  const out = new Float32Array(n);
  for (const note of notes) {
    const f = midi(note) * Math.pow(2, detune / 1200);
    for (let h = 1; h <= 5; h++) {
      const w = (2 * Math.PI * f * h) / SR;
      const a = 1 / (h * h * 0.8 + 0.2);
      for (let i = 0; i < n; i++) out[i] += Math.sin(w * i) * a;
    }
  }
  for (let i = 0; i < n; i++) {
    const tt = i / SR;
    out[i] *= Math.min(1, tt / 1.2) * Math.min(1, Math.max(0, (dur + rel - tt) / rel));
  }
  return filter(out, 'lp', cutoff);
};
const drone = (note, dur) => {
  const n = Math.round(dur * SR);
  const out = new Float32Array(n);
  const f = midi(note);
  for (const d of [-6, 0, 5]) {
    const ff = f * Math.pow(2, d / 1200);
    let ph = (d + 6) / 20;
    for (let i = 0; i < n; i++) {
      ph += ff / SR;
      out[i] += ((ph % 1) * 2 - 1) / 3;
    }
  }
  for (let i = 0; i < n; i++) {
    const tt = i / SR;
    out[i] *= Math.min(1, tt / 1.2) * Math.min(1, (dur - tt) / 1.2);
  }
  return filter(out, 'lp', (q) => 160 + 120 * Math.sin(q * Math.PI * 2) ** 2);
};
// Frame drum: a low thump with a skin slap.
const drum = (dur = 1.2, pitch = 68) => {
  const n = Math.round(dur * SR);
  const out = new Float32Array(n);
  let ph = 0;
  for (let i = 0; i < n; i++) {
    const tt = i / SR;
    ph += (pitch * (1 + 0.6 * Math.exp(-tt * 30))) / SR;
    out[i] = Math.sin(2 * Math.PI * ph) * Math.exp(-tt / 0.32) * Math.min(1, tt / 0.002) + noise() * 0.25 * Math.exp(-tt / 0.02);
  }
  return filter(out, 'lp', 1400);
};
const bell = (note, dur = 2.4, index = 1.1, ratio = 3.5) => {
  const n = Math.round(dur * SR);
  const out = new Float32Array(n);
  const f = midi(note);
  for (let i = 0; i < n; i++) {
    const tt = i / SR;
    const mod = Math.sin(2 * Math.PI * f * ratio * tt) * index * Math.exp(-tt / 0.3);
    out[i] = Math.sin(2 * Math.PI * f * tt + mod) * Math.exp(-tt / (dur * 0.35)) * Math.min(1, tt / 0.003);
  }
  return out;
};
const wood = (pitch = 900) => {
  const n = Math.round(0.25 * SR);
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    const tt = i / SR;
    out[i] = (Math.sin(2 * Math.PI * pitch * tt) * 0.8 + Math.sin(2 * Math.PI * pitch * 2.7 * tt) * 0.3 + noise() * 0.4 * Math.exp(-tt / 0.004)) * Math.exp(-tt / 0.045);
  }
  return filter(out, 'bp', pitch * 1.2, 1.2);
};
const air = (dur, {from = 300, peak = 1800, to = 500, q = 0.9} = {}) => {
  const n = Math.round(dur * SR);
  const raw = new Float32Array(n);
  for (let i = 0; i < n; i++) raw[i] = noise() * Math.pow(Math.sin(Math.PI * Math.min(1, (i / n) * 1.05)), 1.6);
  return filter(raw, 'bp', (p) => (p < 0.6 ? from + (peak - from) * (p / 0.6) : peak + (to - peak) * ((p - 0.6) / 0.4)), q);
};
const click = (freq = 2600) => {
  const n = Math.round(0.03 * SR);
  const raw = new Float32Array(n);
  for (let i = 0; i < n; i++) raw[i] = (noise() * 0.6 + Math.sin((2 * Math.PI * freq * i) / SR) * 0.5) * Math.exp(-(i / SR) / 0.005);
  return filter(raw, 'bp', freq, 1.4);
};

// ---------- score: A minor to C major pop, 96 BPM, confident ----------
// Opens on a hit with the title; the plucked arpeggio and pad run under the question; the kick enters with the
// reasons (R1) and drops out under the name (S8), which resolves on C major.
const BEAT = 60 / 96;
const BAR = BEAT * 4;
const CHORDS = [
  {root: 45, pad: [57, 60, 64, 67], arp: [69, 72, 76, 79]}, // Am7
  {root: 41, pad: [57, 60, 65, 69], arp: [69, 72, 77, 81]}, // Fmaj7
  {root: 36, pad: [55, 60, 64, 67], arp: [67, 72, 76, 79]}, // C
  {root: 43, pad: [55, 59, 62, 67], arp: [67, 71, 74, 79]}, // G
];
const music = makeBus();
const endAt = cues.marks.name;
const kickFrom = S.S2.from;
for (let k = 0; k * BAR < endAt - 0.05; k++) {
  const at = k * BAR;
  const chord = CHORDS[k % 4];
  const len = Math.min(BAR, endAt - at);
  put(music, at, pad(chord.pad, len, -6, 1500), 0.026, -0.6, 0.35);
  put(music, at, pad(chord.pad, len, 6, 1500), 0.026, 0.6, 0.35);
  put(music, at, drone(chord.root - 12, len + 0.6), 0.09, 0, 0.1);
  for (let s8th = 0; s8th < 8; s8th++) {
    const st = at + (s8th * BEAT) / 2;
    if (st >= endAt) break;
    put(music, st, yatga(chord.arp[(s8th * 3) % 4], 0.9, 0.7), 0.075 * (s8th % 2 ? 0.7 : 1), s8th % 2 ? 0.4 : -0.4, 0.3);
    if (st >= kickFrom - 0.01) {
      if (s8th % 4 === 0) put(music, st, drum(0.5, 52), 0.55, 0, 0.05);
      if (s8th % 4 === 2) put(music, st, click(3800), 0.05, 0.25, 0.1);
      if (s8th % 2 === 1) put(music, st, click(7000), 0.025, -0.25, 0.05);
    }
  }
}
// Opening hit and the resolve on C under the name.
put(music, 0.0, drum(1.4, 46), 0.75, 0, 0.2);
[57, 64, 69, 72, 76].forEach((note, i) => put(music, 0.01 + i * 0.025, yatga(note, 2.2, 0.6), 0.16, -0.5 + i * 0.25, 0.4));
[48, 55, 60, 64, 67, 72].forEach((note, i) => put(music, endAt + i * 0.04, yatga(note, 3.6, 0.5), 0.17, -0.5 + i * 0.2, 0.5));
put(music, endAt, pad([48, 55, 60, 64, 67], 3.4, 0, 1500), 0.045, 0, 0.5);
put(music, endAt, drum(1.8, 44), 0.7, 0, 0.25);

const fx = makeBus();
const lr = (p) => -0.6 + 1.2 * p;
for (const e of cues.sfx) {
  if (e.type === 'hit') put(fx, e.at, air(0.5, {from: 1200, peak: 400, to: 200}), 0.25, 0, 0.3);
  if (e.type === 'whoosh') put(fx, e.at - 0.25, air(0.55, {from: 500, peak: 3200, to: 700, q: 1.1}), 0.3, lr, 0.25);
  if (e.type === 'door') put(fx, e.at, wood(620), 0.45, 0, 0.3);
  if (e.type === 'count') [83 + e.k, 90 + e.k].forEach((note, i) => put(fx, e.at + i * 0.06, bell(note, 1.3, 0.9, 3), 0.06, -0.2 + i * 0.4, 0.4));
  if (e.type === 'end') [72, 76, 79, 84].forEach((note, i) => put(fx, e.at + 0.06 * i, bell(note, 3.2, 0.9, 3.5), 0.05, -0.3 + i * 0.2, 0.6));
}

// ---------- mix ----------
const talking = new Uint8Array(Math.ceil(cues.duration * 100) + 1);
for (const [a, b] of speech) for (let i = Math.max(0, Math.floor(a * 100)); i < Math.min(talking.length, Math.ceil(b * 100) + 10); i++) talking[i] = 1;
const score = flatten(music);
let env = 1;
for (let i = 0; i < N; i++) {
  const target = talking[Math.floor(i / 480)] ? 0.55 : 1;
  env += (target - env) * (target < env ? 1 / (0.1 * SR) : 1 / (0.5 * SR));
  const fade = Math.min(1, i / SR / 0.05) * Math.min(1, (cues.duration - i / SR) / 1.6);
  score[0][i] *= env * fade;
  score[1][i] *= env * fade;
}

const STEMS = join(PUB, 'ganaa-house/stems');
mkdirSync(STEMS, {recursive: true});
const writeWav = (file, [l, r], gain = 1) => {
  const data = Buffer.alloc(N * 8);
  for (let i = 0; i < N; i++) {
    data.writeFloatLE(l[i] * gain, i * 8);
    data.writeFloatLE(r[i] * gain, i * 8 + 4);
  }
  const h = Buffer.alloc(44);
  h.write('RIFF', 0);
  h.writeUInt32LE(36 + data.length, 4);
  h.write('WAVEfmt ', 8);
  h.writeUInt32LE(16, 16);
  h.writeUInt16LE(3, 20);
  h.writeUInt16LE(2, 22);
  h.writeUInt32LE(SR, 24);
  h.writeUInt32LE(SR * 8, 28);
  h.writeUInt16LE(8, 32);
  h.writeUInt16LE(32, 34);
  h.write('data', 36);
  h.writeUInt32LE(data.length, 40);
  writeFileSync(join(STEMS, file), Buffer.concat([h, data]));
};
const peak = ([l, r]) => {
  let p = 0;
  for (let i = 0; i < N; i++) p = Math.max(p, Math.abs(l[i]), Math.abs(r[i]));
  return p;
};

writeWav('voice.wav', voice);
writeWav('music.wav', score);
