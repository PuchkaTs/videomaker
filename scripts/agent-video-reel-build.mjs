// Timeline, hook clips and sound for the 12 agent video reels (npm run build:agent-video-reel).
// Reads src/agent-video-reel/offers.json, the voice clips in public/agent-video-reel/vo/ and the Wan talking
// clips in public/agent-video-reel/talk/, and writes:
//   public/agent-video-reel/hook/Vxx.mp4   the talking clip with its silent lead trimmed off (video only)
//   public/agent-video-reel/hook/Vxx.wav   her whispered line, gained, aligned to that clip
//   public/agent-video-reel/stems/         body-voice.wav, body-music.wav, body-sfx.wav (start = end of the hook)
//                                          and hook-bed.wav (10 s, its end sits on the end of the hook)
//   src/agent-video-reel/cues.json         per-version hook length and the shared body timeline
// 48 kHz stereo float. Synth helpers follow scripts/ganaa-reel-v2-build.mjs. Existing hook clips are kept;
// delete public/agent-video-reel/hook/ to re-cut them. Re-run after changing offers.json or a voice take.
