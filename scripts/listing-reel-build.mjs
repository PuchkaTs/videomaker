// Timeline, images and sound for one customer listing reel (node scripts/listing-reel-build.mjs <jobId>).
// Reads public/reel-jobs/<jobId>/brief.json (the order), plan.json (title + beats, written by the worker's
// planning step) and vo/, and writes img/ (normalised photos and tiny blurred backdrops), presenter.jpg,
// stems/ (voice, music, sfx) and cues.json, which is the whole input of the ListingReel composition.
import {execFileSync} from 'node:child_process';
import {copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {SR, air, bass, bell, click, db, decode, drum, duration, flatten, lufs, makeBus, pad, peak, pluck, put, r3, reseed, snare, writeWav} from './lib/synth.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const jobId = process.argv[2];
if (!jobId || !/^[\w-]+$/.test(jobId)) throw new Error('Usage: listing-reel-build.mjs <jobId>');
const REL = `reel-jobs/${jobId}`;
const DIR = join(ROOT, 'public', REL);
const brief = JSON.parse(readFileSync(join(DIR, 'brief.json'), 'utf8'));
const plan = JSON.parse(readFileSync(join(DIR, 'plan.json'), 'utf8'));
const TYPE = {apartment: 'Орон сууц', house: 'Хувийн сууц', office: 'Оффис', commercial: 'Үйлчилгээний талбай', land: 'Газар'};

// ---------- images ----------
mkdirSync(join(DIR, 'img'), {recursive: true});
mkdirSync(join(DIR, 'stems'), {recursive: true});
const sips = (src, out, max) => execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '88', '-Z', String(max), src, '--out', out], {stdio: 'ignore'});
const listing = readdirSync(join(DIR, 'src')).filter((f) => f.startsWith('listing-')).sort();
if (!listing.length) throw new Error('No listing photos');
listing.forEach((f, i) => {
  const out = join(DIR, 'img', `p${i}.jpg`);
  if (!existsSync(out)) sips(join(DIR, 'src', f), out, 1800);
  const blur = join(DIR, 'img', `b${i}.jpg`);
  if (!existsSync(blur)) execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', out, '-vf', 'scale=54:96:force_original_aspect_ratio=increase,crop=54:96,gblur=sigma=3', '-q:v', '4', blur]);
});
const own = brief.presenter.kind === 'own';
const profile = readdirSync(join(DIR, 'src')).find((f) => f.startsWith('profile-'));
if (own && profile) sips(join(DIR, 'src', profile), join(DIR, 'presenter.jpg'), 900);
else copyFileSync(join(ROOT, 'public/agent-video-reel/faces', `${/^V(0[1-9]|1[0-2])$/.test(brief.presenter.modelId) ? brief.presenter.modelId : 'V04'}.jpg`), join(DIR, 'presenter.jpg'));

// ---------- timeline ----------
const TARGET = -17.5;
let t = 0;
const beats = plan.beats.map((beat, i) => {
  const file = join(DIR, 'vo', `b${i}.mp3`);
  const al = JSON.parse(readFileSync(join(DIR, 'vo', `b${i}.json`), 'utf8')).alignment;
  const speechEnd = al.character_end_times_seconds.at(-1);
  const from = t;
  const at = from + (i ? 0.3 : 0.45);
  t = at + speechEnd + (i === plan.beats.length - 1 ? 2.4 : 0.35);
  return {kind: beat.kind, caption: beat.caption, photo: Math.min(listing.length - 1, Math.max(0, beat.photo | 0)), from: r3(from), to: r3(t), at: r3(at), speechEnd, file, gain: TARGET - lufs(file), dur: duration(file)};
});
const total = r3(t);
const cues = {
  _: 'Generated by scripts/listing-reel-build.mjs; do not edit.',
  dir: REL,
  duration: total,
  title: plan.title,
  tag: brief.listing.deal === 'rent' ? 'ТҮРЭЭСЛҮҮЛНЭ' : 'ЗАРНА',
  rent: brief.listing.deal === 'rent',
  type: TYPE[brief.listing.type] ?? '',
  location: brief.listing.location ?? '',
  price: brief.listing.price ?? '',
  agent: {name: brief.agent.name ?? '', phone: brief.agent.phone ?? '', office: brief.agent.office ?? ''},
  presenter: {name: own ? brief.agent.name ?? '' : brief.presenter.name ?? '', own},
  photos: listing.length,
  beats: beats.map(({kind, caption, photo, from, to, at}) => ({kind, caption, photo, from, to, at})),
};

// ---------- sound ----------
reseed(20261119);
const N = Math.ceil(total * SR);
const voice = [new Float32Array(N), new Float32Array(N)];
const talking = new Uint8Array(Math.ceil(total * 100) + 1);
for (const b of beats) {
  const [l, r] = decode(b.file);
  const g = db(b.gain);
  const s = Math.round(b.at * SR);
  for (let i = 0; i < l.length && s + i < N; i++) {
    voice[0][s + i] += l[i] * g;
    voice[1][s + i] += r[i] * g;
  }
  for (let i = Math.floor(b.at * 100); i < Math.min(talking.length, Math.ceil((b.at + b.speechEnd) * 100) + 10); i++) talking[i] = 1;
}
const BEAT = 60 / 100;
const BAR = BEAT * 4;
const CHORDS = [
  {root: 45, pad: [57, 60, 64, 67], arp: [69, 72, 76, 79]},
  {root: 41, pad: [57, 60, 65, 69], arp: [69, 72, 77, 81]},
  {root: 36, pad: [55, 60, 64, 67], arp: [67, 72, 76, 79]},
  {root: 43, pad: [55, 59, 62, 67], arp: [67, 71, 74, 79]},
];
const music = makeBus(N);
const endAt = beats.at(-1).at + beats.at(-1).speechEnd + 0.2;
for (let k = 0; k * BAR < endAt - 0.05; k++) {
  const at = k * BAR;
  const chord = CHORDS[k % 4];
  const len = Math.min(BAR, endAt - at);
  put(music, at, pad(chord.pad, len, -6, 1600), 0.026, -0.6, 0.35);
  put(music, at, pad(chord.pad, len, 6, 1600), 0.026, 0.6, 0.35);
  for (let s8 = 0; s8 < 8; s8++) {
    const st = at + (s8 * BEAT) / 2;
    if (st >= endAt) break;
    put(music, st, pluck(chord.arp[(s8 * 3) % 4], 0.8, 0.7), 0.07 * (s8 % 2 ? 0.7 : 1), s8 % 2 ? 0.4 : -0.4, 0.3);
    if (st >= beats[0].to - 0.01) {
      if (s8 % 4 === 0) put(music, st, drum(0.45, 50), 0.55, 0, 0.04);
      if (s8 === 2 || s8 === 6) put(music, st, snare(), 0.13, 0.1, 0.2);
      if (s8 === 0 || s8 === 3 || s8 === 6) put(music, st, bass(chord.root - 12, BEAT * 0.9), 0.28, 0, 0.02);
    }
  }
}
put(music, 0, drum(1.2, 44), 0.75, 0, 0.2);
[48, 55, 60, 64, 67, 72].forEach((note, i) => put(music, endAt + i * 0.04, pluck(note, 3.0, 0.5), 0.17, -0.5 + i * 0.2, 0.5));
put(music, endAt, pad([48, 55, 60, 64, 67], 2.2, 0, 1600), 0.045, 0, 0.5);
const score = flatten(music);
let env = 1;
for (let i = 0; i < N; i++) {
  const target = talking[Math.floor(i / 480)] ? 0.5 : 1;
  env += (target - env) * (target < env ? 1 / (0.1 * SR) : 1 / (0.5 * SR));
  const fade = Math.min(1, (total - i / SR) / 1.4);
  score[0][i] *= env * fade;
  score[1][i] *= env * fade;
}
const fx = makeBus(N);
beats.forEach((b, i) => {
  if (i) put(fx, b.from - 0.2, air(0.5, {from: 500, peak: 3000, to: 700, q: 1.1}), 0.28, (p) => -0.6 + 1.2 * p, 0.25);
  if (b.kind === 'price') put(fx, b.at + 0.1, drum(1.3, 40), 0.85, 0, 0.3);
  else [81 + (i % 5) * 2, 88 + (i % 5) * 2].forEach((note, k) => put(fx, b.from + 0.25 + k * 0.06, bell(note, 1.1, 0.9, 3), 0.05, -0.2 + k * 0.4, 0.4));
  if (b.kind === 'cta') put(fx, b.at + 0.3, click(3000), 0.6, 0.2, 0.15);
});
put(fx, 0, air(0.5, {from: 1400, peak: 500, to: 200}), 0.3, 0, 0.3);
const STEMS = join(DIR, 'stems');
writeWav(join(STEMS, 'voice.wav'), voice);
writeWav(join(STEMS, 'music.wav'), score);
writeWav(join(STEMS, 'music.wav'), score, db(-26 - lufs(join(STEMS, 'music.wav'))));
const effects = flatten(fx);
writeWav(join(STEMS, 'sfx.wav'), effects, db(-9) / (peak(effects) || 1));
writeFileSync(join(DIR, 'cues.json'), JSON.stringify(cues, null, 1) + '\n');
console.log(`cues.json: ${total} s, ${beats.length} beats, ${listing.length} photos`);
