const cues = {_: 'Generated by scripts/agent-video-reel-build.mjs from offers.json; do not edit.', versions: {}, body: {duration: 0, scenes: [], voices: [], marks: {}, sfx: []}};
for (const offer of plan.offers) {
  const v = voiceMeta(offer.id, offer.take);
  const talk = join(DIR, 'talk', `${offer.id}.mp4`);
  const clipLen = duration(talk);
  // offer.lead: where the voice file starts inside the Wan clip (measured by cross-correlation).
  const trim = Math.max(0, offer.lead + v.first - 0.2);
  const speechEnd = offer.lead + v.speechEnd - trim;
  const hookEnd = speechEnd + 0.12;
  const keep = Math.min(clipLen - trim, hookEnd + 0.5);
  const mp4 = join(DIR, 'hook', `${offer.id}.mp4`);
  if (!existsSync(mp4)) {
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-ss', trim.toFixed(3), '-i', talk, '-t', keep.toFixed(3), '-an', '-c:v', 'libx264', '-crf', '14', '-preset', 'medium', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4]);
  }
  // Her line, aligned to the trimmed clip: the voice file starts at (lead - trim), which may be before 0.
  const [l, r] = decode(v.file);
  const n = Math.ceil((hookEnd + 0.6) * SR);
  const out = [new Float32Array(n), new Float32Array(n)];
  const shift = Math.round((offer.lead - trim) * SR);
  let g = db(WHISPER_TARGET - lufs(v.file));
  g = Math.min(g, db(-1.5) / peak([l, r]));
  for (let i = 0; i < l.length; i++) {
    const j = i + shift;
    if (j < 0 || j >= n) continue;
    out[0][j] = l[i] * g;
    out[1][j] = r[i] * g;
  }
  writeWav(join(DIR, 'hook', `${offer.id}.wav`), out);
  cues.versions[offer.id] = {name: offer.name, text: offer.text, hookEnd: r3(hookEnd), clipLen: r3(keep), speechAt: r3(offer.lead + v.first - trim), gainDb: r3(20 * Math.log10(g))};
}

